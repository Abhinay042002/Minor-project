-- Standard Essentials: Supabase PostgreSQL schema
-- Run this file in Supabase SQL Editor. All privileged writes are protected by RLS.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  category text not null,
  description text not null default '',
  image text not null default '',
  price numeric(12,2) not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  rating numeric(2,1) not null default 0 check (rating between 0 and 5),
  specs jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wishlists (
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, product_id)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(comment) between 2 and 2000),
  created_at timestamptz not null default now(),
  unique (product_id, user_id)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique default ('SE-' || upper(substr(encode(gen_random_bytes(6),'hex'),1,10))),
  user_id uuid not null default auth.uid() references public.profiles(id),
  customer_name text not null,
  customer_email text not null,
  shipping_address text not null,
  payment_method text not null,
  subtotal numeric(12,2) not null,
  discount numeric(12,2) not null default 0,
  tax numeric(12,2) not null,
  total numeric(12,2) not null,
  coupon_code text,
  status text not null default 'Confirmed' check (status in ('Confirmed','Processing','Shipped','Delivered','Cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  product_image text not null default '',
  unit_price numeric(12,2) not null,
  quantity integer not null check (quantity > 0)
);

create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists reviews_product_idx on public.reviews(product_id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Keep product ratings in sync with review rows.
create or replace function public.refresh_product_rating()
returns trigger language plpgsql security definer set search_path = public
as $$
declare target_id bigint;
begin
  target_id := coalesce(new.product_id, old.product_id);
  update public.products
  set rating = coalesce((select round(avg(rating)::numeric,1) from public.reviews where product_id = target_id),0)
  where id = target_id;
  return coalesce(new, old);
end;
$$;

drop trigger if exists reviews_refresh_rating on public.reviews;
create trigger reviews_refresh_rating after insert or update or delete on public.reviews
for each row execute procedure public.refresh_product_rating();

-- Prices and totals are calculated in Postgres, never trusted from the browser.
create or replace function public.place_order(
  p_customer_name text,
  p_customer_email text,
  p_shipping_address text,
  p_payment_method text,
  p_coupon_code text,
  p_items jsonb
) returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2) := 0;
  v_tax numeric(12,2) := 0;
  v_total numeric(12,2) := 0;
begin
  if auth.uid() is null then raise exception 'Please sign in before placing an order'; end if;
  if length(trim(p_customer_name)) < 2 or position('@' in p_customer_email) < 2 or length(trim(p_shipping_address)) < 8 then
    raise exception 'Please provide valid contact and delivery details';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Your cart is empty';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty < 1 or v_qty > 25 then raise exception 'Invalid item quantity'; end if;
    select * into v_product from public.products
      where id = (v_item->>'product_id')::bigint and active = true for update;
    if not found then raise exception 'A product is no longer available'; end if;
    if v_product.stock < v_qty then raise exception 'Insufficient stock for %', v_product.name; end if;
    v_subtotal := v_subtotal + v_product.price * v_qty;
  end loop;

  if upper(coalesce(p_coupon_code,'')) = 'WELCOME10' then v_discount := round(v_subtotal * 0.10,2);
  elsif upper(coalesce(p_coupon_code,'')) = 'SAVE20' then v_discount := round(v_subtotal * 0.20,2);
  end if;
  v_tax := round((v_subtotal - v_discount) * 0.18,2);
  v_total := v_subtotal - v_discount + v_tax;

  insert into public.orders(user_id,customer_name,customer_email,shipping_address,payment_method,subtotal,discount,tax,total,coupon_code)
  values(auth.uid(),trim(p_customer_name),trim(p_customer_email),trim(p_shipping_address),trim(p_payment_method),v_subtotal,v_discount,v_tax,v_total,nullif(upper(p_coupon_code),'')) returning * into v_order;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_qty := (v_item->>'quantity')::integer;
    select * into v_product from public.products where id = (v_item->>'product_id')::bigint for update;
    update public.products set stock = stock - v_qty, updated_at = now() where id = v_product.id;
    insert into public.order_items(order_id,product_id,product_name,product_image,unit_price,quantity)
    values(v_order.id,v_product.id,v_product.name,v_product.image,v_product.price,v_qty);
  end loop;

  return jsonb_build_object(
    'id',v_order.id,'order_number',v_order.order_number,'created_at',v_order.created_at,
    'customer_name',v_order.customer_name,'customer_email',v_order.customer_email,
    'shipping_address',v_order.shipping_address,'payment_method',v_order.payment_method,
    'subtotal',v_order.subtotal,'discount',v_order.discount,'tax',v_order.tax,'total',v_order.total,
    'coupon_code',v_order.coupon_code,'status',v_order.status
  );
end;
$$;

create or replace function public.is_store_admin() returns boolean language sql stable security definer set search_path = public as $ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin'); $;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.wishlists enable row level security;
alter table public.reviews enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "profiles read own or admin" on public.profiles for select using (id = auth.uid() or public.is_store_admin());
create policy "profiles update own name" on public.profiles for update using (id = auth.uid()) with check (id = auth.uid() and role = 'customer');

create policy "products public read active" on public.products for select using (active = true or public.is_store_admin());
create policy "products admin insert" on public.products for insert with check (public.is_store_admin());
create policy "products admin update" on public.products for update using (public.is_store_admin()) with check (public.is_store_admin());
create policy "products admin delete" on public.products for delete using (public.is_store_admin());

create policy "wishlist own rows" on public.wishlists for select using (user_id=auth.uid());
create policy "wishlist own insert" on public.wishlists for insert with check (user_id=auth.uid());
create policy "wishlist own delete" on public.wishlists for delete using (user_id=auth.uid());

create policy "reviews public read" on public.reviews for select using (true);
create policy "reviews authenticated insert own" on public.reviews for insert with check (user_id=auth.uid());
create policy "reviews owner delete" on public.reviews for delete using (user_id=auth.uid());

create policy "orders customer or admin read" on public.orders for select using (user_id=auth.uid() or public.is_store_admin());
create policy "orders admin update" on public.orders for update using (public.is_store_admin()) with check (public.is_store_admin());

create policy "order items owner or admin read" on public.order_items for select using (
  exists(select 1 from public.orders o where o.id=order_id and (o.user_id=auth.uid() or public.is_store_admin()))
);

grant usage on schema public to anon, authenticated;
grant select on public.products to anon, authenticated;
grant select, insert, update, delete on public.profiles, public.products, public.wishlists, public.reviews, public.orders, public.order_items to authenticated;
grant usage, select on all sequences in schema public to authenticated;
grant execute on function public.place_order(text,text,text,text,text,jsonb) to authenticated;
